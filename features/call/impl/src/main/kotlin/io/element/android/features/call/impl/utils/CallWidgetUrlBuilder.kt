package io.element.android.features.call.impl.utils

/**
 * Builds the final Element Call widget URL used by the WebView.
 *
 * Element Call v0.21.0 renders its home page for the `/` path, and that page is the only place
 * where `fet()` (and therefore `createRoom()`) can be triggered. Using the `/room/` path makes
 * React Router render the call view instead, so no room is ever requested by the widget.
 */
internal object CallWidgetUrlBuilder {
    private const val EMBEDDED_CALL_HOST = "call.fionaro.pw"
    private const val ANDROID_ASSET_HOST = "appassets.androidplatform.net"
    private const val SKIP_LOBBY_PARAM = "skipLobby"
    private val skipLobbyRegex = Regex("([?&])$SKIP_LOBBY_PARAM=[^&]*")

    /**
     * @param callUrl URL generated by the Rust SDK widget.
     * @return the URL with the call view path and `skipLobby=true` applied.
     */
    fun build(callUrl: String): String {
        val hostedUrl = callUrl.replace(ANDROID_ASSET_HOST, EMBEDDED_CALL_HOST)
        val callViewUrl = hostedUrl.replace(
            "$EMBEDDED_CALL_HOST/#?",
            "$EMBEDDED_CALL_HOST/room/#?",
        )
        return callViewUrl.withSkipLobby()
    }

    private fun String.withSkipLobby(): String {
        if (skipLobbyRegex.containsMatchIn(this)) {
            // Force the value instead of appending a second parameter: URLSearchParams#get returns
            // the first occurrence, so appending would not override an existing skipLobby=false.
            return replace(skipLobbyRegex) { match -> "${match.groupValues[1]}$SKIP_LOBBY_PARAM=true" }
        }
        val separator = when {
            endsWith("?") || endsWith("&") -> ""
            contains("?") -> "&"
            else -> "?"
        }
        return "$this$separator$SKIP_LOBBY_PARAM=true"
    }
}
